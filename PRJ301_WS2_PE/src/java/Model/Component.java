package Model;

/**
 *
 * @author plmin
 */
public class Component {

    private String id;
    private String product;
    private String brand;

    public Component() {
    }

    public Component(String id, String product, String brand) {
        this.id = id;
        this.product = product;
        this.brand = brand;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getProduct() {
        return product;
    }

    public void setProduct(String product) {
        this.product = product;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    @Override
    public String toString() {
        return "Components{" + "id=" + id + ", product=" + product + ", brand=" + brand + '}';
    }
}
