// _______________ 8. Toán tử so sánh SPECIAL _______________
/*
- Loại toán tử so sánh này so sánh cả TYPE và VALUE của data
    ===
    !==
*/
var h = '1';
var i = 1;
console.log('Output cho phep so sanh \'1\' === 1: ', h === i); // -> false, String != number
console.log('Output cho phep so sanh \'1\' == 1: ', h == i); // -> true, 1 = 1
